using System.Globalization;
using Microsoft.Extensions.Logging;
using Phantom.Engine.Core;
using Phantom.Relay.Lsfg.Upscaling;
using Phantom.Relay.Profiles;
using Phantom.Relay.Stream.Media.Gpu;

namespace Phantom.Relay.Desktop.Pictures;

/// <summary>
/// Lossless Scaling's upscalers on the decoder's GPU path, as the renderer asks for them (<see cref="PictureScale"/>):
/// set up for the picture's size and the window's on the decoder's device when either or the method changes
/// (<see cref="Apply"/>), then each picture (decoded, or generated by the frame generation) upscaled into a slot of the
/// shared ring, which is then made at the output's size (<see cref="SlotWidth"/> x <see cref="SlotHeight"/>: NV12 wants
/// even sizes, the picture fills the slot's top-left corner). When anything it needs is missing (Lossless Scaling not
/// installed, shaders that do not fit, a ring the video processor cannot write) it logs why once and the pictures go at
/// their own size, which the renderer then upscales itself; <see cref="Describe"/> says what it does for the stats.
/// Decode thread only, but <see cref="Describe"/>.
/// </summary>
internal sealed class UpscaledPictures : IDisposable
{
    // NV12 has a chroma sample per 2 x 2 pixels, so its textures have even sizes.
    private const int Nv12Alignment = 2;

    private readonly ILogger _log;
    private LosslessUpscaleStage? _stage;
    private PictureScale _scale = PictureScale.None;
    private string _state = string.Empty;
    private double _milliseconds;

    public UpscaledPictures(ILogger log)
    {
        _log = log;
    }

    /// <summary>Whether pictures are upscaled now.</summary>
    public bool IsOn => _stage is not null;

    /// <summary>The upscaled picture's size (the window's rectangle).</summary>
    public int Width => _scale.Width;

    public int Height => _scale.Height;

    /// <summary>The ring's slot size while upscaling: the output's, rounded up to even.</summary>
    public int SlotWidth => Even(_scale.Width);

    public int SlotHeight => Even(_scale.Height);

    /// <summary>The picture size the stage was made for.</summary>
    public int InputWidth { get; private set; }

    public int InputHeight { get; private set; }

    /// <summary>Whether <see cref="Apply"/> would make the stage again for this request and picture size.</summary>
    public bool Differs(PictureScale scale, int width, int height)
    {
        return !ReferenceEquals(scale, _scale) || width != InputWidth || height != InputHeight;
    }

    /// <summary>Sets the upscaler up as <paramref name="scale"/> asks, for pictures of <paramref name="width"/> x <paramref name="height"/> on <paramref name="device"/>.</summary>
    public void Apply(PictureScale scale, nint device, int width, int height)
    {
        Close();
        (_scale, InputWidth, InputHeight) = (scale, width, height);

        if (!scale.IsOn)
        {
            Volatile.Write(ref _state, string.Empty);

            return;
        }

        if (scale.Width <= width || scale.Height <= height)
        {
            Off($"the window shows the picture no larger than {width}x{height}");

            return;
        }

        var geometry = new LosslessUpscaleGeometry(width, height, scale.Width, scale.Height, SlotWidth, SlotHeight);
        _stage = LosslessUpscaleStage.TryCreate(device, Settings(scale), geometry, _log, out var problem);

        if (_stage is null)
        {
            Off(problem ?? "the upscaler could not be made");

            return;
        }

        Volatile.Write(ref _state, string.Create(CultureInfo.InvariantCulture, $"{Label(scale)} → {scale.Width}x{scale.Height}"));
        _log.UpscaleOn(scale.Method, width, height, scale.Width, scale.Height);
    }

    /// <summary>The upscaler cannot run after all (<paramref name="reason"/>): the pictures go at their own size.</summary>
    public void Refuse(string reason)
    {
        Close();
        Off(reason);
    }

    /// <summary>A picture's work starts (its GPU time is taken from here).</summary>
    [HotPath]
    public void Begin()
    {
        _stage!.Begin();
    }

    /// <summary>Upscales the decoded picture (slice <paramref name="slice"/> of <paramref name="surface"/>) into <paramref name="nv12"/>, a slot of the ring.</summary>
    [HotPath]
    public bool Write(nint surface, uint slice, nint nv12)
    {
        return _stage!.Write(surface, slice, nv12);
    }

    /// <summary>Upscales an RGBA picture of the input size (a generated frame) into <paramref name="nv12"/>.</summary>
    [HotPath]
    public bool WriteRgba(nint rgba, nint nv12)
    {
        return _stage!.WriteRgba(rgba, nv12);
    }

    /// <summary>The picture's work is queued: its GPU time is read once it is back.</summary>
    [HotPath]
    public void Done()
    {
        _stage!.Done();
        Volatile.Write(ref _milliseconds, _stage.LastGpuMilliseconds);
    }

    /// <summary>"LS1 → 3600x2025 0.21 ms" while it runs, "LS1 off: why" when it cannot, empty when not asked for; any thread.</summary>
    public string Describe()
    {
        var state = Volatile.Read(ref _state);

        if (!IsOn)
        {
            return state;
        }

        return string.Create(CultureInfo.InvariantCulture, $"{state} {Volatile.Read(ref _milliseconds):F2} ms");
    }


    public void Dispose()
    {
        Close();
    }

    // "LS1 (network 2)", "LS1 performance (network 2)", "SGSR".
    private static string Label(PictureScale scale)
    {
        if (scale.Method == UpscaleMethod.Sgsr)
        {
            return scale.Method.Label();
        }

        return string.Create(CultureInfo.InvariantCulture, $"{scale.Method.Label()} (network {scale.Strength})");
    }

    private static LosslessUpscalerSettings Settings(PictureScale scale)
    {
        var kind = scale.Method switch
        {
            UpscaleMethod.Ls1Performance => LosslessUpscalerKind.Ls1Performance,
            UpscaleMethod.Sgsr => LosslessUpscalerKind.Sgsr,
            _ => LosslessUpscalerKind.Ls1,
        };

        return LosslessUpscalerSettings.Default with { Kind = kind, Level = scale.Strength };
    }

    private static int Even(int size)
    {
        return (size + Nv12Alignment - 1) / Nv12Alignment * Nv12Alignment;
    }

    private void Close()
    {
        _stage?.Dispose();
        _stage = null;
    }

    private void Off(string reason)
    {
        Volatile.Write(ref _state, $"{_scale.Method.Label()} off: {reason}");
        _log.UpscaleOff(_scale.Method, reason);
    }
}
